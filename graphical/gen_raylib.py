#!/usr/bin/env python3
"""Generate funcbuild bindings for raylib from its own API dump.

Reads raylib's machine-readable API (parser/output/raylib_api.json) and emits
a C file of fb_CFunction wrappers plus raylib_register(fb_State*) that registers
every supported function and enum constant.

Marshalling:
  scalars / enums          <-> fb Int      (float is lossy: fb has no float
                                             runtime value; whole numbers ok)
  const char *             <-> fb String
  plain-data structs       <-> fb Map (per field)          e.g. Color, Vector2
  resource structs (with   <-> fb object, whole struct boxed by value into
    pointer/array fields)      native data (opaque)         e.g. Texture, Font
  void                      -> nil
Anything else (out-pointers, buffers, callbacks, varargs, arrays) is skipped.
Only marshalling helpers actually referenced by a bound function are emitted.
"""
import json, sys, os, subprocess

API = os.path.expanduser("~/projects/raylib/parser/output/raylib_api.json")
LIB = os.path.expanduser("~/projects/raylib/src/libraylib.a")
OUT = os.path.join(os.path.dirname(__file__), "raylib_gen.c")

# symbols actually defined in the built library (the API dump can be a newer
# raylib than the compiled lib -- only bind what will link).
libsyms = None
try:
    nm = subprocess.run(["nm", "-g", LIB], capture_output=True, text=True).stdout
    libsyms = {p[-1] for p in (l.split() for l in nm.splitlines())
               if len(p) >= 3 and p[-2] in ("T", "t", "W")}
except Exception:
    pass

d = json.load(open(API))
structs = {s["name"]: s for s in d["structs"]}
enums   = d["enums"]
aliases = {a["name"]: a["type"] for a in d["aliases"]}

INT_SCALARS = {"int","unsigned int","char","unsigned char","short","unsigned short",
               "long","unsigned long","long long","unsigned long long","size_t"}
FLOAT_SCALARS = {"float","double"}
enum_names = {e["name"] for e in enums}

def resolve(t):
    t = t.strip()
    return resolve(aliases[t]) if t in aliases else t

# classify structs as "value" (all fields marshallable, no pointers) or "resource"
def field_ok_value(ftype, value_structs):
    t = resolve(ftype)
    if "*" in t or "[" in t: return False
    return (t == "bool" or t in INT_SCALARS or t in FLOAT_SCALARS
            or t in enum_names or t in value_structs)

value_structs, changed = set(), True
while changed:
    changed = False
    for name, s in structs.items():
        if name not in value_structs and all(field_ok_value(f["type"], value_structs) for f in s["fields"]):
            value_structs.add(name); changed = True
resource_structs = set(structs) - value_structs

def cat(t):
    t = resolve(t)
    if t == "void": return ("void", t)
    if t == "bool": return ("bool", t)
    if t == "const char *": return ("str", t)
    if t in INT_SCALARS: return ("int", t)
    if t in FLOAT_SCALARS: return ("float", t)
    if t in enum_names: return ("int", "int")
    if t in value_structs: return ("vstruct", t)
    if t in resource_structs: return ("rstruct", t)
    return ("hard", t)

def supported(f):
    if libsyms is not None and f["name"] not in libsyms:
        return False
    types = [f["returnType"]] + [p["type"] for p in f.get("params", [])]
    return all(cat(t)[0] != "hard" for t in types)

funcs_ok   = [f for f in d["functions"] if supported(f)]
funcs_skip = [f["name"] for f in d["functions"] if not supported(f)]

# which struct helpers are actually needed, by direction: a returned struct
# needs pack/box, a parameter struct needs unpack/unbox.
need_pack, need_unpack, need_box, need_unbox = set(), set(), set(), set()
def note_ret(t):
    k, ct = cat(t)
    if k == "vstruct": need_pack.add(ct)
    elif k == "rstruct": need_box.add(ct)
def note_param(t):
    k, ct = cat(t)
    if k == "vstruct": need_unpack.add(ct)
    elif k == "rstruct": need_unbox.add(ct)
for f in funcs_ok:
    note_ret(f["returnType"])
    for p in f.get("params", []): note_param(p["type"])
def close(s):                        # nested value-struct fields need the same op
    changed = True
    while changed:
        changed = False
        for name in list(s):
            for fl in structs[name]["fields"]:
                k, ct = cat(fl["type"])
                if k == "vstruct" and ct not in s:
                    s.add(ct); changed = True
close(need_pack); close(need_unpack)
used_r = need_box | need_unbox
used_v = need_pack | need_unpack

# ---- emit --------------------------------------------------------------------
out = []
w = out.append
w("/* GENERATED by gen_raylib.py from raylib_api.json -- do not edit. */")
w('#include <stdlib.h>')
w('#include "fbuild.h"')
w('#include "raylib.h"')
w("")

for name in sorted(used_r):
    w(f"static fb_Class cls_{name};")
if used_r: w("")
for name in sorted(need_box):
    w(f"static fb_Value box_{name}(fb_State *S, {name} v){{ {name} *p = malloc(sizeof v); *p = v; return fb_object(S, cls_{name}, p); }}")
for name in sorted(need_unbox):
    w(f"static {name} unbox_{name}(fb_Value o){{ return *({name} *)fb_object_data(o); }}")
if used_r: w("")

for name in sorted(need_pack):
    w(f"static fb_Value pack_{name}(fb_State *S, {name} v);")
for name in sorted(need_unpack):
    w(f"static {name} unpack_{name}(fb_Value m);")
if used_v: w("")

def fields_of(s):
    for f in s["fields"]:
        for fn in f["name"].split(","):
            yield fn.strip(), f["type"]

for name in sorted(need_pack):
    w(f"static fb_Value pack_{name}(fb_State *S, {name} v) {{")
    w(f"\tfb_Value m = fb_map(S);")
    for fn, ft in fields_of(structs[name]):
        k, ct = cat(ft)
        val = (f"pack_{ct}(S, v.{fn})" if k == "vstruct" else f"fb_int(S, (long)v.{fn})")
        w(f'\tfb_set(S, m, "{fn}", {val});')
    w("\treturn m;\n}")
for name in sorted(need_unpack):
    w(f"static {name} unpack_{name}(fb_Value m) {{")
    w(f"\t{name} v;")
    for fn, ft in fields_of(structs[name]):
        k, ct = cat(ft); get = f'fb_field(m, "{fn}")'
        rhs = (f"unpack_{ct}({get})" if k == "vstruct" else f"({resolve(ft)})fb_toint({get})")
        w(f"\tv.{fn} = {rhs};")
    w("\treturn v;\n}")
if used_v: w("")

def arg_expr(ptype, i):
    k, ct = cat(ptype); a = f"a[{i}]"
    if k == "int":     return f"({resolve(ptype)})fb_toint({a})"
    if k == "float":   return f"({resolve(ptype)})fb_toint({a})"
    if k == "bool":    return f"(bool)fb_toint({a})"
    if k == "str":     return f"fb_tostr(S, {a})"
    if k == "vstruct": return f"unpack_{ct}({a})"
    if k == "rstruct": return f"unbox_{ct}({a})"
    return "0"

for f in funcs_ok:
    name, params = f["name"], f.get("params", [])
    call = f"{name}(" + ", ".join(arg_expr(p["type"], i) for i, p in enumerate(params)) + ")"
    rk, rct = cat(f["returnType"])
    w(f"static fb_Value l_{name}(fb_State *S, fb_Value *a, int n) {{ (void)a; (void)n;")
    if   rk == "void":    w(f"\t{call}; return fb_nil(S);")
    elif rk == "bool":    w(f"\treturn fb_bool(S, {call});")
    elif rk == "str":     w(f"\treturn fb_str(S, {call});")
    elif rk == "vstruct": w(f"\treturn pack_{rct}(S, {call});")
    elif rk == "rstruct": w(f"\treturn box_{rct}(S, {call});")
    else:                 w(f"\treturn fb_int(S, (long){call});")   # int/float/enum
    w("}")
w("")

enum_consts = [(v["name"], v["value"]) for e in enums for v in e["values"]]
for nm, val in enum_consts:
    w(f"static fb_Value e_{nm}(fb_State *S, fb_Value *a, int n) {{ (void)a; (void)n; return fb_int(S, {val}); }}")
w("")

w("void raylib_register(fb_State *S) {")
for name in sorted(used_r):
    w(f'\tcls_{name} = fb_class(S, "{name}");')
for f in funcs_ok:
    np = len(f.get("params", []))
    w(f'\tfb_register(S, &(fb_Reg){{ "{f["name"]}", l_{f["name"]}, {np}, {np}, FB_RET_ANY, 0 }});')
for nm, _ in enum_consts:
    w(f'\tfb_register(S, &(fb_Reg){{ "{nm}", e_{nm}, 0, 0, FB_RET_INT, 0 }});')
w("}")

open(OUT, "w").write("\n".join(out) + "\n")
print(f"wrote {OUT}", file=sys.stderr)
print(f"functions: {len(funcs_ok)} bound, {len(funcs_skip)} skipped", file=sys.stderr)
print(f"structs used: {len(used_v)} value, {len(used_r)} resource "
      f"(of {len(value_structs)}/{len(resource_structs)} total)", file=sys.stderr)
print(f"enum constants: {len(enum_consts)}", file=sys.stderr)
